def build_iso_excel(output_path: str):
    """Generates the master 93-control ISO/IEC 27002:2022 Excel workbook with Swiss Civic styling."""
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "ISO 27002_2022 Controls"

    # Style definitions
    header_fill = PatternFill(start_color="1D4ED8", end_color="1D4ED8", fill_type="solid") # Civic Cobalt
    header_font = Font(name="Segoe UI", size=11, bold=True, color="FFFFFF")
    data_font = Font(name="Segoe UI", size=10)
    mono_font = Font(name="Consolas", size=10, bold=True)
    border_side = Side(border_style="thin", color="D8D6CE")
    cell_border = Border(left=border_side, right=border_side, top=border_side, bottom=border_side)
    wrap_alignment = Alignment(vertical="top", wrap_text=True)

    columns = [
        ("Chapter", 22),
        ("Control ID", 14),
        ("Control Title", 32),
        ("Type", 14),
        ("Cybersecurity Concept", 20),
        ("Operational Capability", 24),
        ("Security Domain", 22),
        ("Plain English Requirement", 50),
        ("Sub-Controls Checklist", 40),
        ("Typical Municipal Evidence", 35),
        ("Common Real-World Gaps", 40),
        ("Recommended Consulted Roles", 35),
        ("Pragmatic Compensating Controls", 45),
    ]

    # Write headers
    for col_idx, (col_name, width) in enumerate(columns, start=1):
        cell = ws.cell(row=1, column=col_idx, value=col_name)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        col_letter = get_column_letter(col_idx)
        ws.column_dimensions[col_letter].width = width

    ws.row_dimensions[1].height = 30

    # Write data rows
    for row_idx, item in enumerate(ISO_27002_CONTROLS, start=2):
        ws.cell(row=row_idx, column=1, value=item["chapter"]).font = data_font
        id_cell = ws.cell(row=row_idx, column=2, value=item["control_id"])
        id_cell.font = mono_font
        id_cell.alignment = Alignment(horizontal="center", vertical="top")

        ws.cell(row=row_idx, column=3, value=item["title"]).font = Font(name="Segoe UI", size=10, bold=True)
        ws.cell(row=row_idx, column=4, value=item["type"]).font = data_font
        ws.cell(row=row_idx, column=5, value=item["concept"]).font = data_font
        ws.cell(row=row_idx, column=6, value=item["capability"]).font = data_font
        ws.cell(row=row_idx, column=7, value=item["domain"]).font = data_font
        ws.cell(row=row_idx, column=8, value=item["requirement"]).font = data_font
        ws.cell(row=row_idx, column=9, value=item["sub_controls"]).font = data_font
        ws.cell(row=row_idx, column=10, value=item["evidence"]).font = data_font
        ws.cell(row=row_idx, column=11, value=item["common_gaps"]).font = data_font
        ws.cell(row=row_idx, column=12, value=item["consult_roles"]).font = data_font
        ws.cell(row=row_idx, column=13, value=item["compensating_controls"]).font = data_font

        for col_idx in range(1, 14):
            c = ws.cell(row=row_idx, column=col_idx)
            c.border = cell_border
            if col_idx != 2:
                c.alignment = wrap_alignment

        ws.row_dimensions[row_idx].height = 55

    ws.freeze_panes = "A2"
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    wb.save(output_path)
    print(f"Master ISO 27002:2022 workbook successfully written to: {output_path}")

if __name__ == "__main__":
    out_file = os.path.join("data", "iso_checklists", "ISO_27002_2022_Master_Checklist.xlsx")
    build_iso_excel(out_file)
